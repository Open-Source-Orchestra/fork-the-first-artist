#!/usr/bin/env node
// Generates cloudflare/src/garden-stewards.ts from the public garden roster
// (frontend/public/data/artists.json). ONLY public profile fields are copied; the 0G steward
// Worker grounds each artist's *preview* steward on exactly these facts and nothing else.
//
//   node cloudflare/scripts/gen-garden-stewards.mjs           # (re)write the file
//   node cloudflare/scripts/gen-garden-stewards.mjs --check   # exit 1 if the file drifted from the roster
//
// Public garden data is NOT consent: these stewards are labelled "preview" and never claim to
// speak for the artist. Slugs in EXCLUDED are held back entirely (e.g. until an artist confirms).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const ROSTER_PATH = resolve(here, '../../frontend/public/data/artists.json');
export const OUT_PATH = resolve(here, '../src/garden-stewards.ts');

/** Held back from every steward surface. perrie: not on the schedule until she confirms her visa. */
export const EXCLUDED = Object.freeze(['perrie']);
/** Slugs with a hand-written steward in zero-g.ts (not generated). */
export const HAND_WRITTEN = Object.freeze(['mira-modal']);

const SLUG_RE = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;
const MAX_TEXT = 400;

/** Trimmed single-line text without control characters; '' for anything that isn't a string. */
export function cleanText(value, max = MAX_TEXT) {
  if (typeof value !== 'string' && typeof value !== 'number') return '';
  // eslint-disable-next-line no-control-regex
  return String(value).replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
}

/** Display name without emoji (e.g. "Shaka 🤙" → "Shaka"). */
export function cleanName(value) {
  return cleanText(value, 120).replace(/[\p{Extended_Pictographic}\u{1F3FB}-\u{1F3FF}️‍]/gu, '').replace(/\s+/g, ' ').trim();
}

/** https-only URL without credentials, normalised; null otherwise. */
export function httpsUrl(value) {
  if (typeof value !== 'string') return null;
  try {
    const u = new URL(value.trim());
    if (u.protocol !== 'https:' || u.username || u.password) return null;
    return u.href;
  } catch {
    return null;
  }
}

/**
 * `links` is not always an array in the roster: some entries carry the string "[]", others
 * could carry a single {label,url} object or a {label: url} map. Accept all, keep https only.
 */
export function cleanLinks(raw) {
  let value = raw;
  if (typeof value === 'string') {
    try { value = JSON.parse(value); } catch { value = httpsUrl(value) ? [{ label: 'link', url: value }] : []; }
  }
  let list = [];
  if (Array.isArray(value)) list = value;
  else if (value && typeof value === 'object') {
    list = 'url' in value ? [value] : Object.entries(value).map(([label, url]) => ({ label, url }));
  }
  const out = [];
  const seen = new Set();
  for (const item of list) {
    const link = typeof item === 'string' ? { label: 'link', url: item } : item;
    if (!link || typeof link !== 'object') continue;
    const url = httpsUrl(link.url);
    if (!url || seen.has(url)) continue;
    seen.add(url);
    out.push({ label: cleanText(link.label, 120) || new URL(url).hostname, url });
    if (out.length >= 8) break;
  }
  return out;
}

/** Public profile fields only — no photo paths, codes, riders or anything else. */
export function buildProfiles(roster) {
  const artists = Array.isArray(roster?.artists) ? roster.artists : [];
  const out = [];
  const seen = new Set();
  for (const a of artists) {
    if (!a || typeof a !== 'object') continue;
    const slug = typeof a.slug === 'string' ? a.slug : '';
    if (!SLUG_RE.test(slug) || EXCLUDED.includes(slug) || HAND_WRITTEN.includes(slug) || seen.has(slug)) continue;
    const name = cleanName(a.name);
    if (!name) continue;
    seen.add(slug);
    out.push({
      slug,
      name,
      role: cleanText(a.role),
      status: cleanText(a.status, 120),
      set: cleanText(a.set),
      tagline: cleanText(a.tagline),
      headline: cleanText(a.headline),
      links: cleanLinks(a.links),
      profile: httpsUrl(a.profile),
    });
  }
  return out;
}

export function render(profiles) {
  return `// GENERATED by cloudflare/scripts/gen-garden-stewards.mjs from frontend/public/data/artists.json.
// Do not edit by hand: change the roster, then run \`node cloudflare/scripts/gen-garden-stewards.mjs\`.
// ONLY public garden-profile fields. Public garden data is not consent: every artist here gets a
// *preview* steward until they activate their own. Held back (not generated): ${EXCLUDED.join(', ')}.

export interface GardenLink {
  readonly label: string;
  readonly url: string;
}

export interface GardenProfile {
  readonly slug: string;
  readonly name: string;
  readonly role: string;
  readonly status: string;
  readonly set: string;
  readonly tagline: string;
  readonly headline: string;
  readonly links: readonly GardenLink[];
  readonly profile: string | null;
}

export const GARDEN_EXCLUDED: readonly string[] = ${JSON.stringify(EXCLUDED)};

export const GARDEN_PROFILES: readonly GardenProfile[] = ${JSON.stringify(profiles, null, 2)};
`;
}

export function generate(rosterPath = ROSTER_PATH) {
  return render(buildProfiles(JSON.parse(readFileSync(rosterPath, 'utf8'))));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT_PATH, 'utf8'); } catch {}
    if (current !== next) {
      console.error('garden-stewards.ts is out of date with frontend/public/data/artists.json — run: node cloudflare/scripts/gen-garden-stewards.mjs');
      process.exit(1);
    }
    console.log('garden-stewards.ts matches the roster');
  } else {
    writeFileSync(OUT_PATH, next);
    console.log(`wrote ${OUT_PATH}`);
  }
}
